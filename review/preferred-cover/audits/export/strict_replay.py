"""Strict, one-worker replay of all stored full-parent sorted guard transports.

No solver is invoked. Every formula and lifted binary proof is regenerated by
lift_sorted.replay, but its checker callback is replaced with drat-trim -i -U
(without -w). Receipts and CLI logs are retained under strict_logs/.
"""
import gzip
import hashlib
import json
import subprocess
import sys
from pathlib import Path

HERE = Path(__file__).resolve().parent
ROOT = HERE / "bundle/K58_wall_10k_batches"
sys.path.insert(0, str(ROOT))

import lift_sorted
from common import OUT, sha

LOGS = HERE / "strict_logs"
LOGS.mkdir(exist_ok=True)
records = []
current = {"name": None}


def strict_rup(query, proof, extra=()):
    assert list(extra) == ["-U"], extra
    cmd = [str(ROOT / "tools/drat-trim"), str(query), str(proof), "-i", "-U"]
    assert "-w" not in cmd
    run = subprocess.run(cmd, capture_output=True)
    output = (run.stdout or b"") + (run.stderr or b"")
    name = current["name"] + ".log"
    (LOGS / name).write_bytes(b"COMMAND: " + " ".join(cmd).encode() + b"\n" + output)
    assert run.returncode == 0, (current["name"], run.returncode, output[-2000:])
    assert b"s VERIFIED" in output.splitlines(), (current["name"], output[-2000:])
    assert b"s NOT VERIFIED" not in output
    current["checks"] += 1
    return True


lift_sorted.rup = strict_rup
paths = sorted((OUT / "physical-replays").glob("*.json"))
assert len(paths) == 42, len(paths)
for i, path in enumerate(paths, 1):
    stored = json.loads(path.read_text())
    current = {"name": path.stem, "checks": 0}
    fresh = lift_sorted.replay((stored["row_id"], stored["w"], stored["z"]))
    assert fresh == stored, (path, fresh, stored)
    lifted = gzip.decompress(path.with_suffix(".rup.gz").read_bytes())
    assert sha(lifted) == stored["lifted_rup_sha256"]
    assert current["checks"] == 1
    records.append({"receipt": path.name, "row_id": stored["row_id"],
                    "words": [stored["w"], stored["z"]],
                    "parent_sha256": stored["raw_parent_sha256"],
                    "query_sha256": stored["query_sha256"],
                    "lifted_rup_sha256": stored["lifted_rup_sha256"],
                    "strict_command_options": ["-i", "-U"],
                    "result": "s VERIFIED", "log": str((LOGS / (path.stem + ".log")).relative_to(HERE))})
    print(i, len(paths), path.stem, "s VERIFIED (-i -U; no -w)", flush=True)

summary = {"proofs": len(records), "all_receipts_regenerated_exactly": True,
           "drat_trim_sha256": hashlib.sha256((ROOT / "tools/drat-trim").read_bytes()).hexdigest(),
           "checks": records}
(HERE / "strict_replay_output.json").write_text(json.dumps(summary, indent=2, sort_keys=True) + "\n")
print(json.dumps({"proofs": len(records), "all_receipts_regenerated_exactly": True}, sort_keys=True))

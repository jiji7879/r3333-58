#!/usr/bin/env bash
set -euo pipefail
M=$(cd "$(dirname "$0")" && pwd)
ROOT=$(cd "$M/../../.." && pwd)
PY=${K58_PYTHON:-"$ROOT/.scratch/shared-learning-pilot/K58_shared_learning/.venv/bin/python"}
ROW=06861a3df60c08e409dd61965819af321f109e9b82bfd3bc5d05b2645362ec06
cd "$M"
sha256sum --check EXPECTED_SHA256
"$PY" -B -c 'import pysat; assert pysat.__version__ == "1.9.dev22"'
TMP=$(mktemp -d "$M/results/reproduce.XXXXXX")
trap 'rm -rf "$TMP"' EXIT
for STYLE in naive naive-split boundary; do
  "$PY" -B src/two5_wall_encoder.py "$ROW" --mode two5 \
    --conditionalization "$STYLE" --out "$TMP/$STYLE.cnf" > "$TMP/$STYLE.out"
  cmp "$TMP/$STYLE.cnf" "results/wall-two5-$STYLE.cnf"
done
"$PY" -B src/audit_wall.py > results/audit.log
"$PY" -B src/audit_order.py > results/audit-order.log
"$PY" -B src/summarize_results.py > results/analysis-summary.log
printf 'PASS: exact parent/queries, regenerated bytes, projection/order audits, and receipt summary\n'
printf 'Benchmarks are checked from retained raw receipts, not rerun by this quick script.\n'

#!/usr/bin/env python3
"""Toy controls for the one-colour lex-leader rule used on the K58 parent.

The rule ("certificate = forced-equal prefix, then a strict (1,0) difference")
can be validated *completely* on a small instance, which is impossible on K58.
Toy: edge 4-colourings of K5 with no monochromatic triangle (the same
"4 colours, no mono triangle" predicate family as the K58 parent, without its
root units), candidate group generated by the transposition p = (3 4).

  T1 complete rule check : over ALL 2^10 colour-0 words, the rule fires iff
                           L(p.G) < L(G), with the true first-difference witness.
  T2 clause validity     : every generated clause holds at every orbit-minimal
                           model of the invariant model set.
  T3 orbit survival      : on the invariant model set every p-orbit keeps a
                           representative satisfying all generated clauses.
  T4 non-invariant set   : adding the (non-p-invariant) condition colour(0,4)=0
                           destroys that guarantee for some orbit, so the
                           survival test has teeth.
  T5 single sign flip    : flipping one literal of one generated clause destroys
                           the guarantee, so the test detects one-bit corruption.
"""
import json
from itertools import combinations, product
from pathlib import Path

HERE = Path(__file__).resolve().parent
N = 5
COLOURS = 4
PAIRS = list(combinations(range(N), 2))
INDEX = {pair: r for r, pair in enumerate(PAIRS)}
PERM = list(range(N))
PERM[3], PERM[4] = 4, 3
INV = [0] * N
for u, w in enumerate(PERM):
    INV[w] = u
PHI = [INDEX[(min(INV[u], INV[v]), max(INV[u], INV[v]))] for u, v in PAIRS]
TRIANGLES = list(combinations(range(N), 3))
EDGE = {pair: r for r, pair in INDEX.items()}
MAX_FREE_ROWS = 3
MAX_LENGTH = 12


def lex_compare(word):
    image = [word[PHI[r]] for r in range(len(PAIRS))]
    for r in range(len(PAIRS)):
        if image[r] != word[r]:
            return r, image[r] == 0 and word[r] == 1
    return None


def certificate(assign):
    prefix = []
    for r in range(len(PAIRS)):
        other = PHI[r]
        if other == r:
            continue
        a, b = assign.get(r), assign.get(other)
        if a is None or b is None:
            return None
        if a != b:
            if a == 1 and b == 0:
                return prefix + [(r, 1), (other, 0)], r
            return None
        prefix.extend([(r, a), (other, b)])
    return None


def clause_of(entries):
    seen, out = set(), []
    for r, value in entries:
        if r in seen:
            continue
        seen.add(r)
        out.append(-(r + 1) if value else r + 1)
    return tuple(out)


def generate():
    out = {}
    assign = {}

    def consider():
        got = certificate(assign)
        if got:
            key = tuple(sorted(clause_of(got[0])))
            if 2 <= len(key) <= MAX_LENGTH:
                out.setdefault(key, got[1])

    def walk(index, free_rows):
        while index < len(PAIRS):
            r, other = index, PHI[index]
            if other == r:
                index += 1
                continue
            a, b = assign.get(r), assign.get(other)
            if a is not None and b is not None:
                if a == b:
                    index += 1
                    continue
                if a == 1 and b == 0:
                    consider()
                return
            options = []
            if a is None and b is None:
                options.append({r: 1, other: 0})
            elif a == 1:
                options.append({other: 0})
            elif b == 0:
                options.append({r: 1})
            for extra in options:
                assign.update(extra)
                consider()
                for k in extra:
                    del assign[k]
            if free_rows >= MAX_FREE_ROWS:
                return
            for value in (0, 1):
                extra = {}
                if a is None:
                    extra[r] = value
                if b is None:
                    extra[other] = value
                assign.update(extra)
                walk(index + 1, free_rows + 1)
                for k in extra:
                    del assign[k]
            return
    walk(0, 0)
    return out


def sat(clause, word):
    for literal in clause:
        r = abs(literal) - 1
        if (literal > 0) == (word[r] == 1):
            return True
    return False


def main():
    report = {}
    # T1 complete rule check
    bad = 0
    for bits in product((0, 1), repeat=len(PAIRS)):
        word = list(bits)
        got = certificate({r: word[r] for r in range(len(PAIRS))})
        cmp = lex_compare(word)
        decrease = cmp is not None and cmp[1]
        if decrease != (got is not None) or (got is not None and got[1] != cmp[0]):
            bad += 1
    report["T1_rule_mismatches_over_1024_words"] = bad

    clauses = generate()
    report["generated_clauses"] = len(clauses)
    lengths = {}
    for clause in clauses:
        lengths[len(clause)] = lengths.get(len(clause), 0) + 1
    report["lengths"] = lengths

    def good(colours):
        for tri in TRIANGLES:
            a, b, c = (INDEX[(x, y)] for x, y in combinations(tri, 2))
            if colours[a] == colours[b] == colours[c]:
                return False
        return True

    models = [c for c in product(range(COLOURS), repeat=len(PAIRS)) if good(c)]
    report["models_invariant"] = len(models)

    # two non-p-invariant restrictions: the earlier edge and the later edge
    noninv = [c for c in models if c[INDEX[(0, 3)]] == 0]
    noninv_late = [c for c in models if c[INDEX[(0, 4)]] == 0]
    report["models_with_colour_0_3_equal_0"] = len(noninv)
    report["models_with_colour_0_4_equal_0"] = len(noninv_late)

    def word(colours):
        return [1 if c == 0 else 0 for c in colours]

    def orbits(collection):
        seen, groups = set(), []
        for colours in collection:
            if colours in seen:
                continue
            image = tuple(colours[PHI[r]] if False else
                          colours[INDEX[(min(PERM[u], PERM[v]), max(PERM[u], PERM[v]))]]
                          for u, v in PAIRS)
            group = {colours, image}
            seen |= group
            groups.append(sorted(group))
        return groups

    def survival(collection, clause_set, name):
        member = set(collection)
        groups = orbits(collection)
        empty = 0
        multiplicity = {}
        for group in groups:
            keep = [m for m in group if m in member and all(sat(c, word(m)) for c in clause_set)]
            multiplicity[len(keep)] = multiplicity.get(len(keep), 0) + 1
            if not keep:
                empty += 1
        report[name] = {"orbits": len(groups), "empty_orbits": empty,
                        "models_in_set": len(member),
                        "representatives_per_orbit": dict(sorted(multiplicity.items()))}
        return empty

    survival(models, list(clauses), "T3_invariant_set")
    survival(noninv, list(clauses), "T4a_noninvariant_early_edge")
    survival(noninv_late, list(clauses), "T4b_noninvariant_late_edge")

    shortest = min(clauses, key=len)
    flipped = list(shortest)
    flipped[0] = -flipped[0]
    survival(models, [tuple(flipped)] + [c for c in clauses if c != shortest],
             "T5_single_sign_flip")

    violations = 0
    for group in orbits(models):
        minimum = min(group, key=word)
        violations += sum(1 for c in clauses if not sat(c, word(minimum)))
    report["T2_violations_at_orbit_minima"] = violations
    report["sample_clauses"] = [list(c) for c in sorted(clauses, key=len)[:4]]
    (HERE / "toy_receipt.json").write_text(json.dumps(report, indent=2, sort_keys=True) + "\n")
    print(json.dumps(report, indent=2, sort_keys=True))


if __name__ == "__main__":
    main()
